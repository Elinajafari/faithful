"""Regenerate lib/faithful_consensus.py from the contract.

    python scripts/lift.py

The lifted module claims to be the faithfulness rules "as the contract
runs them". Maintaining it by hand makes that claim false the first time
somebody edits one side, so it is generated, and
tests/test_logic.py::TestTheLiftedLib compares the two parsed trees function by
function. scripts/mutate.py runs this inside every mutated copy, so the lib
parity test can never stand in for the behavioural test a mutation deserves.
"""

import ast
import pathlib

ROOT = pathlib.Path(__file__).absolute().parent.parent
CONTRACT = ROOT / "faithful.py"
OUT = ROOT / "lib" / "faithful_consensus.py"

CONSTANTS = [
    "FAITHFUL", "UNFAITHFUL", "FORWARD", "REVERSED", "OPTION_TEXT", "MAX_ATTEMPTS", "MAX_REASON",
]

FUNCTIONS = [
    "normalise_choice", "option_of", "fold", "ruling_sound", "faithful_agrees", "outcome",
    "sanitise_reason", "fence", "build_prompt",
]

HEADER = '''# faithful_consensus.py - the faithfulness rules, lifted out to be copied.
#
# GENERATED by scripts/lift.py from faithful.py. Do not edit by hand:
# tests/test_logic.py compares the two parsed trees function by function.
#
# GenLayer contracts run as ONE Python file inside the GenVM. There is no
# cross-file import at deploy time, so this is not a module a contract imports:
# it is a curated block, for reading and lifting into another project without
# reading a whole contract first.
#
# Everything here is pure. No storage, no network, no model.
#
# The ideas worth lifting: the model is asked whether one text says what
# another says, choosing between two options the contract wrote, and is never
# shown the fee, the parties or the attempt number; fold() puts a disagreement
# between the two orders into the VALUE (unfaithful: the translator who wants
# to be paid carries the burden); and outcome() decides, by counting attempts,
# whether a ruling pays, refunds, or allows one more try.

'''


def main():
    src = CONTRACT.read_text(encoding="utf-8")
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)

    def segment(node, with_comments=False):
        start = node.lineno - 1
        while with_comments and start > 0 and lines[start - 1].startswith("#"):
            start -= 1
        return "".join(lines[start:node.end_lineno]).rstrip("\n")

    parts = []
    for name in CONSTANTS:
        for n in tree.body:
            if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in n.targets):
                parts.append(segment(n))
                break
        else:
            raise SystemExit(f"the contract no longer defines {name}")

    fns = []
    for name in FUNCTIONS:
        for n in tree.body:
            if isinstance(n, ast.FunctionDef) and n.name == name:
                fns.append(segment(n, with_comments=True))
                break
        else:
            raise SystemExit(f"the contract no longer defines {name}()")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n".join(parts) + "\n\n\n" + "\n\n\n".join(fns) + "\n",
                   encoding="utf-8", newline="\n")
    print(f"  {OUT.relative_to(ROOT).as_posix()}: {len(CONSTANTS)} constants, {len(FUNCTIONS)} functions")


if __name__ == "__main__":
    main()
